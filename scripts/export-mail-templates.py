"""Regenerate src/growth/mailTemplates.ts from backend/app/mail_html.py.

The frontend demo is a static mock and cannot import Python, so it keeps a
generated copy of the branded bodies. Run this after editing the backend
markup:

    backend/.venv/bin/python scripts/export-mail-templates.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.mail import TEMPLATE_KEYS  # noqa: E402
from app.mail_html import template_html  # noqa: E402

TARGET = ROOT / "src" / "growth" / "mailTemplates.ts"
HEADER = '''// Generated by scripts/export-mail-templates.py from backend/app/mail_html.py.
// Do not edit by hand: update the Python builder and re-run the script.
export const DEFAULT_TEMPLATE_HTML: Record<string, string> = {
'''


def main() -> None:
    chunks = [HEADER]
    for key in TEMPLATE_KEYS:
        html = template_html(key)
        for token in ("`", "${"):
            if token in html:
                raise SystemExit(f"{key} contains {token!r}; choose another quoting style")
        chunks.append(f"  {key}: `{html}`,\n")
    chunks.append("};\n")
    TARGET.write_text("".join(chunks), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
